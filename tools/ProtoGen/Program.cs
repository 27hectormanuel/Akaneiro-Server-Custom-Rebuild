// ProtoGen: derives the server side of the Akaneiro protocol from the generated client protocol code.
//
// The client files (written by the original "ProtocolGen 1.3") contain
//   - *_SendRequest:     client -> server packet writers
//   - *_ReceiveCallback: server -> client packet parsers
// This tool inverts both, producing for the server
//   - I<Name>RequestHandler + <Name>RequestDispatcher: parses client -> server packets
//   - <Name>Responses:                                 writes server -> client packets
//
// Usage: dotnet run --project tools/ProtoGen -- <client CS/Protocol dir> <output dir>

using System.Text;
using System.Text.RegularExpressions;

internal static class Program
{
    private sealed record Param(string Type, string Name);

    private sealed record Message(string Name, string MethodIdConst, List<Param> Params, List<string> Statements);

    private static int Main(string[] args)
    {
        if (args.Length != 2)
        {
            Console.Error.WriteLine("usage: ProtoGen <client protocol dir> <output dir>");
            return 1;
        }

        string inDir = args[0];
        string outDir = args[1];
        Directory.CreateDirectory(outDir);

        Generate(Path.Combine(inDir, "ProtocolGameServer_Client.cs"), "Game", "ProtocolGame", Path.Combine(outDir, "GameProtocol.g.cs"));
        Generate(Path.Combine(inDir, "ProtocolBattle_Client.cs"), "Battle", "ProtocolBattle", Path.Combine(outDir, "BattleProtocol.g.cs"));
        return 0;
    }

    private static void Generate(string inFile, string name, string prefix, string outFile)
    {
        string src = File.ReadAllText(inFile);
        List<Message> requests = ParseRequests(src, prefix);
        List<Message> responses = ParseResponses(src, prefix);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> by tools/ProtoGen from " + Path.GetFileName(inFile) + ". Do not edit. </auto-generated>");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.AppendLine("namespace Akaneiro.Server.Protocol");
        sb.AppendLine("{");

        // Request handler interface.
        sb.AppendLine($"    /// <summary>Client -> server messages of the {name} protocol.</summary>");
        sb.AppendLine($"    public interface I{name}RequestHandler");
        sb.AppendLine("    {");
        foreach (Message m in requests)
            sb.AppendLine($"        void {m.Name}({ParamList(m.Params)});");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Base class: every request is reported as unhandled unless overridden.
        sb.AppendLine($"    public abstract class {name}RequestHandlerBase : I{name}RequestHandler");
        sb.AppendLine("    {");
        sb.AppendLine("        protected abstract void OnUnhandled(string request);");
        foreach (Message m in requests)
            sb.AppendLine($"        public virtual void {m.Name}({ParamList(m.Params)}) => OnUnhandled(\"{m.Name}\");");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Dispatcher.
        sb.AppendLine($"    public static class {name}RequestDispatcher");
        sb.AppendLine("    {");
        sb.AppendLine("        public static readonly Dictionary<int, string> Names = new Dictionary<int, string>");
        sb.AppendLine("        {");
        foreach (Message m in requests)
            sb.AppendLine($"            {{ {m.MethodIdConst}, \"{m.Name}\" }},");
        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("        /// <summary>Reads the method id and dispatches. Returns false for unknown ids (packet read position is then after the id).</summary>");
        sb.AppendLine($"        public static bool Dispatch(Packet pak, I{name}RequestHandler handler)");
        sb.AppendLine("        {");
        sb.AppendLine("            int methodID = pak.ReadInt();");
        sb.AppendLine("            switch (methodID)");
        sb.AppendLine("            {");
        foreach (Message m in requests)
        {
            sb.AppendLine($"                case {m.MethodIdConst}:");
            sb.AppendLine("                {");
            foreach (Param p in m.Params)
                sb.AppendLine($"                    {p.Type} {p.Name} = {DefaultValue(p.Type)};");
            foreach (string st in m.Statements)
                sb.AppendLine("                    " + InvertWrite(st) + ";");
            sb.AppendLine($"                    handler.{m.Name}({string.Join(", ", m.Params.Select(p => p.Name))});");
            sb.AppendLine("                    return true;");
            sb.AppendLine("                }");
        }
        sb.AppendLine("            }");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Response writers.
        sb.AppendLine($"    /// <summary>Server -> client messages of the {name} protocol.</summary>");
        sb.AppendLine($"    public static class {name}Responses");
        sb.AppendLine("    {");
        sb.AppendLine("        public static readonly Dictionary<int, string> Names = new Dictionary<int, string>");
        sb.AppendLine("        {");
        foreach (Message m in responses)
            sb.AppendLine($"            {{ {m.MethodIdConst}, \"{m.Name}\" }},");
        sb.AppendLine("        };");
        foreach (Message m in responses)
        {
            sb.AppendLine();
            sb.AppendLine($"        public static Packet {m.Name}({ParamList(m.Params)})");
            sb.AppendLine("        {");
            sb.AppendLine("            Packet stream = new Packet();");
            sb.AppendLine("            stream.WriteInt(0);");
            sb.AppendLine("            stream.WriteShort(0);");
            sb.AppendLine($"            stream.WriteInt({m.MethodIdConst});");
            foreach (string st in m.Statements)
                sb.AppendLine("            " + InvertRead(st) + ";");
            sb.AppendLine("            stream.Patch(stream.get_used_size() - 6, 0);");
            sb.AppendLine("            return stream;");
            sb.AppendLine("        }");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");

        File.WriteAllText(outFile, sb.ToString());
        Console.WriteLine($"{Path.GetFileName(outFile)}: {requests.Count} requests, {responses.Count} responses");
    }

    // ---- client -> server (from *_SendRequest) --------------------------------------------------

    private static readonly Regex RequestMethod = new Regex(
        @"public static Packet\s+(\w+)\s*\(([^)]*)\)\s*\{(.*?)return stream;",
        RegexOptions.Singleline);

    private static List<Message> ParseRequests(string src, string prefix)
    {
        int start = src.IndexOf($"class {prefix}_SendRequest", StringComparison.Ordinal);
        int end = src.IndexOf($"class {prefix}_ReceiveCallback", StringComparison.Ordinal);
        string section = src.Substring(start, end - start);

        var result = new List<Message>();
        foreach (Match m in RequestMethod.Matches(section))
        {
            List<Param> ps = ParseParamList(m.Groups[2].Value);
            List<string> statements = SplitStatements(m.Groups[3].Value);

            int idIdx = statements.FindIndex(s => s.Contains("uMethodID_"));
            string idConst = Regex.Match(statements[idIdx], @"(\w+_METHOD\.uMethodID_\w+)").Groups[1].Value;
            List<string> fields = statements
                .Skip(idIdx + 1)
                .TakeWhile(s => !s.StartsWith("size =", StringComparison.Ordinal))
                .ToList();

            result.Add(new Message(m.Groups[1].Value, idConst, ps, fields));
        }
        return result;
    }

    // stream.WriteInt(x)          -> x = pak.ReadInt()
    // stream.WriteFloat(pos.x)    -> pos.x = pak.ReadFloat()
    // T.Write(stream, x)          -> T.Read(pak, out x)
    private static string InvertWrite(string st)
    {
        Match prim = Regex.Match(st, @"^stream\.Write(\w+)\((.+)\)$");
        if (prim.Success)
            return $"{prim.Groups[2].Value} = pak.Read{prim.Groups[1].Value}()";

        Match complex = Regex.Match(st, @"^([\w.]+)\.Write\(stream,\s*(\w+)\)$");
        if (complex.Success)
            return $"{complex.Groups[1].Value}.Read(pak, out {complex.Groups[2].Value})";

        throw new InvalidDataException("Unsupported request statement: " + st);
    }

    // ---- server -> client (from *_ReceiveCallback) ---------------------------------------------

    private static readonly Regex ParseMethod = new Regex(
        @"static void __parse__On_(\w+)\s*\(Packet ins,\s*\w+ receiver\)\s*\{(.*?)receiver\.On_\w+\s*\(([^)]*)\);",
        RegexOptions.Singleline);

    private static List<Message> ParseResponses(string src, string prefix)
    {
        // Method ids come from the dispatch switch: "case X_METHOD.uMethodID_Y: __parse__On_Z(".
        var ids = new Dictionary<string, string>();
        foreach (Match c in Regex.Matches(src, @"case (\w+_METHOD\.uMethodID_\w+)\s*:\s*__parse__On_(\w+)\s*\("))
            ids[c.Groups[2].Value] = c.Groups[1].Value;

        var result = new List<Message>();
        foreach (Match m in ParseMethod.Matches(src))
        {
            string name = m.Groups[1].Value;
            if (!ids.TryGetValue(name, out string idConst))
                throw new InvalidDataException("No method id for response " + name);

            var types = new Dictionary<string, string>();
            var reads = new List<string>();
            foreach (string st in SplitStatements(m.Groups[2].Value))
            {
                // "UnityEngine.Vector3 pos = new UnityEngine.Vector3()" or "int x"
                Match decl = Regex.Match(st, @"^([\w.<>\[\]]+)\s+(\w+)(\s*=\s*new .*)?$");
                if (decl.Success && !st.Contains("ins."))
                {
                    types[decl.Groups[2].Value] = decl.Groups[1].Value;
                    continue;
                }
                reads.Add(st);
            }

            var ps = m.Groups[3].Value
                .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .Select(n => new Param(types[n], n))
                .ToList();

            result.Add(new Message(name, idConst, ps, reads));
        }
        return result;
    }

    // x = ins.ReadInt()          -> stream.WriteInt(x)
    // pos.x = ins.ReadFloat()    -> stream.WriteFloat(pos.x)
    // T.Read(ins, out x)         -> T.Write(stream, x)
    private static string InvertRead(string st)
    {
        Match prim = Regex.Match(st, @"^([\w.]+)\s*=\s*ins\.Read(\w+)\(\)$");
        if (prim.Success)
            return $"stream.Write{prim.Groups[2].Value}({prim.Groups[1].Value})";

        Match complex = Regex.Match(st, @"^([\w.]+)\.Read\(ins,\s*out\s+(\w+)\)$");
        if (complex.Success)
            return $"{complex.Groups[1].Value}.Write(stream, {complex.Groups[2].Value})";

        throw new InvalidDataException("Unsupported response statement: " + st);
    }

    // ---- helpers --------------------------------------------------------------------------------

    private static List<string> SplitStatements(string body)
    {
        // Strip line comments, then split on ';'.
        body = Regex.Replace(body, @"//[^\n]*", "");
        return body.Split(';')
            .Select(s => Regex.Replace(s, @"\s+", " ").Trim())
            .Where(s => s.Length > 0 && s != "{" && s != "}")
            .Select(s => s.TrimStart('{', ' ').TrimEnd('}', ' '))
            .Where(s => s.Length > 0)
            .ToList();
    }

    private static List<Param> ParseParamList(string list)
    {
        return list
            .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(p =>
            {
                int sp = p.LastIndexOf(' ');
                return new Param(p.Substring(0, sp).Trim(), p.Substring(sp + 1).Trim());
            })
            .ToList();
    }

    private static string ParamList(List<Param> ps) => string.Join(", ", ps.Select(p => $"{p.Type} {p.Name}"));

    private static string DefaultValue(string type) => type switch
    {
        "string" => "\"\"",
        "UnityEngine.Vector3" => "new UnityEngine.Vector3()",
        _ => "default",
    };
}
